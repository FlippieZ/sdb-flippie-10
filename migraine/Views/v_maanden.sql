CREATE VIEW migraine.v_maanden AS
	SELECT 1 AS mndNr, 'Januari' AS mndNaam
	UNION
	SELECT 2 AS mndNr, 'Februari' AS mndNaam
	UNION
	SELECT 3 AS mndNr, 'Maart' AS mndNaam
	UNION
	SELECT 4 AS mndNr, 'April' AS mndNaam
	UNION
	SELECT 5 AS mndNr, 'Mei' AS mndNaam
	UNION
	SELECT 6 AS mndNr, 'Juni' AS mndNaam
	UNION
	SELECT 7 AS mndNr, 'Juli' AS mndNaam
	UNION
	SELECT 8 AS mndNr, 'Augustus' AS mndNaam
	UNION
	SELECT 9 AS mndNr, 'September' AS mndNaam
	UNION
	SELECT 10 AS mndNr, 'Oktober' AS mndNaam
	UNION
	SELECT 11 AS mndNr, 'November' AS mndNaam
	UNION
	SELECT 12 AS mndNr, 'December' AS mndNaame

GO

